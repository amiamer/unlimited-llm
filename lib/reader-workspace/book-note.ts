/**
 * Reader Workspace — Book_Note serialization + pagination.
 * Feature: reader-workspace
 *
 * Every document has ONE logical Book_Note that mirrors the reader's current
 * local annotation set. It is regenerated from scratch on every change
 * (regenerate-from-local-set), so deletes truly remove content. When the
 * content exceeds the Obsidian per-note limit it is split across sequentially
 * numbered pages — `{title}`, `{title} (2)`, … — and NO annotation content is
 * ever dropped (Requirements 6.1, 6.6).
 *
 * All pages live under the `reading/annotations` folder of the vault (the
 * folder the agent context loads). The folder is baked into the page title so
 * BOTH the create (POST) and stale-page cleanup (DELETE) paths — which each
 * derive their filesystem target from `bookNotePageTitle` — resolve to the
 * same place.
 *
 * The LocalObsidianService writes directly to the filesystem — there is no
 * per-note size limit from the file system. The pagination threshold exists
 * only to keep individual notes reasonably sized; it is set high enough that
 * typical annotation sets (including long AI replies) fit in a single note.
 */

import type { Annotation } from './types';

export const BOOK_NOTE_BANNER =
  '> auto-generated by the reader — do not hand-edit (your changes will be overwritten)';

export const OBSIDIAN_TASK_LIMIT = 100_000;

/**
 * Hard ceiling on the displayed title length. Bounds the per-page header so
 * the body always has a usable budget even for pathologically long document
 * titles. Deterministic, so page titles stay stable across regenerations.
 */
const MAX_TITLE_LEN = 200;

/**
 * Vault folder that holds every reading annotation note. Baked into the page
 * title (as a folder-qualified path) so the LocalObsidianService writes here
 * instead of the default AI-Notes folder — and so stale-page cleanup deletes
 * from here too. This is the single, canonical location for reading notes.
 */
export const READING_NOTES_FOLDER = 'reading/annotations';

/** One paginated page of the single logical Book_Note. */
export interface BookNotePage {
  /**
   * Folder-qualified page title. Page 1: `reading/annotations/{title}`;
   * page n>1: `reading/annotations/{title} ({n})`. The service turns the last
   * path segment into the `.md` filename and the leading segments into the
   * target folder — so no `Reading:`/colon appears in the filename anymore.
   */
  title: string;
  /** Full POST payload for this page; guaranteed <= OBSIDIAN_TASK_LIMIT. */
  task: string;
}

/** Deterministic, folder-qualified page title for a 1-based page number. */
export function bookNotePageTitle(docTitle: string, pageNumber: number): string {
  const base = (docTitle ?? '').slice(0, MAX_TITLE_LEN).trim() || 'Untitled';
  const name = pageNumber <= 1 ? base : `${base} (${pageNumber})`;
  return `${READING_NOTES_FOLDER}/${name}`;
}

/**
 * Render one annotation as a markdown block: the quoted passage, the comment,
 * then each AI reply in order. Contains the comment text and every reply's
 * content verbatim so the no-drop completeness property holds (Req 5.3/6.4).
 */
export function renderAnnotationBlock(a: Annotation): string {
  const lines: string[] = [];
  const passage = (a.selectedText ?? '').trim();
  if (passage) {
    // Quote the passage so it reads as the anchored excerpt.
    lines.push(passage.split('\n').map((l) => `> ${l}`).join('\n'));
    lines.push('');
  }
  lines.push((a.comment ?? '').trim());
  // AI replies are kept in the note, clearly demarcated, with the follow-up
  // question (if any) that produced each one.
  for (const reply of a.aiReplies ?? []) {
    lines.push('');
    if (reply.prompt) lines.push(`**Q:** ${reply.prompt.trim()}`);
    lines.push(`**AI:** ${(reply.content ?? '').trim()}`);
  }
  return lines.join('\n').trim();
}

const BLOCK_SEPARATOR = '\n\n---\n\n';

// ── Article vault note ───────────────────────────────────────────────────────

// Wikipedia section headings that are boilerplate — skip them in vault notes.
const SKIP_VAULT_HEADINGS = new Set([
  'References', 'Notes', 'See also', 'Further reading',
  'External links', 'Bibliography', 'Footnotes', 'Citations',
  'Sources', 'Works cited',
]);

/**
 * Render clean article sentences as markdown.
 * Boilerplate Wikipedia sections (References, See also, etc.) are omitted.
 * @param headingPrefix - prefix for section headings (default `##`; use `###`
 *   when the body is nested inside a `## article` section).
 */
export function articleBodyMarkdown(
  sentences: string[],
  paragraphBreaks: Set<number>,
  headingIndices: Set<number>,
  listItemIndices: Set<number>,
  headingPrefix = '##',
): string {
  const parts: string[] = [];
  let paraSentences: string[] = [];
  let inList = false;
  let skipUntilNextHeading = false;

  const flushPara = () => {
    if (paraSentences.length > 0) {
      parts.push(paraSentences.join(' '));
      paraSentences = [];
    }
  };

  for (let i = 0; i < sentences.length; i++) {
    const s = sentences[i];

    if (headingIndices.has(i)) {
      flushPara();
      inList = false;
      if (SKIP_VAULT_HEADINGS.has(s)) {
        skipUntilNextHeading = true;
        continue;
      }
      skipUntilNextHeading = false;
      parts.push(`${headingPrefix} ${s}`);
      continue;
    }

    if (skipUntilNextHeading) continue;

    if (listItemIndices.has(i)) {
      if (!inList) flushPara();
      parts.push(`- ${s}`);
      inList = true;
      continue;
    }

    if (paragraphBreaks.has(i) && i > 0) {
      flushPara();
      inList = false;
    }

    paraSentences.push(s);
  }

  flushPara();
  return parts.join('\n\n');
}

// ── Inline-link helpers for vault article notes ─────────────────────────────

/** Returns true if the annotation comment marks this highlight as a wikilink. */
export function isLinkAnnotation(comment: string): boolean {
  const c = comment.trim();
  return /^link$/i.test(c) || /^link[:\s]/i.test(c) || c.includes('[[');
}

/**
 * Build the `[[...]]` wikilink form for a link annotation.
 *
 * When `linkTarget` is provided (new-style annotation from the Link button):
 *   - empty linkTarget  →  [[selectedText]]
 *   - "Some Term"       →  [[Some Term|selectedText]]
 *
 * When falling back to `comment` text (old-style "link" annotations):
 *   - bare "link"       →  [[selectedText]]
 *   - "link: Some Term" →  [[Some Term|selectedText]]
 *   - comment has [[T]] →  [[T|selectedText]]
 */
export function computeWikilink(selectedText: string, comment: string, linkTarget?: string): string {
  if (linkTarget !== undefined) {
    const t = linkTarget.trim().replace(/^\[\[|\]\]$/g, '').trim();
    // A target equal to the selected text adds nothing — emit a single
    // [[selected text]] rather than the redundant [[x|x]].
    if (!t || t === selectedText) return `[[${selectedText}]]`;
    return `[[${t}|${selectedText}]]`;
  }
  const raw = comment.trim();
  if (/^link$/i.test(raw)) return `[[${selectedText}]]`;
  const colonMatch = raw.match(/^link:\s*(.+)$/i);
  if (colonMatch) {
    const term = colonMatch[1].trim().replace(/^\[\[|\]\]$/g, '').trim();
    return term ? `[[${term}|${selectedText}]]` : `[[${selectedText}]]`;
  }
  const wikiMatch = raw.match(/\[\[([^\]]+)\]\]/);
  if (wikiMatch) return `[[${wikiMatch[1].trim()}|${selectedText}]]`;
  return `[[${selectedText}]]`;
}

export interface LinkAnnotation {
  selectedText: string;
  wikilink: string;
  startSentenceIndex: number;
  endSentenceIndex: number;
}

/**
 * Render article sentences as markdown, then inject Obsidian [[wikilinks]] for
 * flagged highlights. Boilerplate Wikipedia sections are omitted.
 *
 * Two-phase approach: first render to a plain string, then do a full-string
 * text search for each link. This avoids a sentence-index mismatch bug where
 * annotation indices (from the annotated reader view) differ from those
 * produced by re-extracting sentences at save time, which caused the
 * per-paragraph range check to skip every paragraph.
 */
export function buildArticleBodyWithLinks(
  sentences: string[],
  paragraphBreaks: Set<number>,
  headingIndices: Set<number>,
  listItemIndices: Set<number>,
  headingLevels: Map<number, number>,
  linkAnnotations: LinkAnnotation[] = [],
): string {
  // Phase 1 — render plain markdown (no links)
  const parts: string[] = [];
  let paraSentences: string[] = [];
  let inList = false;
  let skipUntilNextHeading = false;

  const flushPara = () => {
    if (paraSentences.length === 0) return;
    parts.push(paraSentences.join(' '));
    paraSentences = [];
  };

  for (let i = 0; i < sentences.length; i++) {
    const s = sentences[i];

    if (headingIndices.has(i)) {
      flushPara();
      inList = false;
      if (SKIP_VAULT_HEADINGS.has(s)) { skipUntilNextHeading = true; continue; }
      skipUntilNextHeading = false;
      parts.push(`${'#'.repeat(headingLevels.get(i) ?? 2)} ${s}`);
      continue;
    }

    if (skipUntilNextHeading) continue;

    if (listItemIndices.has(i)) {
      if (!inList) flushPara();
      parts.push(`- ${s}`);
      inList = true;
      continue;
    }

    if (paragraphBreaks.has(i) && i > 0) { flushPara(); inList = false; }
    paraSentences.push(s);
  }

  flushPara();
  let md = parts.join('\n\n');

  // Phase 2 — inject [[wikilinks]] on the full rendered string.
  // Each injection targets the first occurrence that is NOT already inside an
  // existing [[ ]] span, so links never nest and the same text is never wrapped
  // twice.
  for (const link of linkAnnotations) {
    const sel = link.selectedText;
    if (!sel) continue;

    const ranges = wikilinkRanges(md);
    const insideLink = (start: number, end: number): boolean =>
      ranges.some(([s, e]) => start < e && end > s);

    // Exact match (common case) — first occurrence outside any existing link.
    let injected = false;
    for (let from = md.indexOf(sel); from !== -1; from = md.indexOf(sel, from + 1)) {
      const end = from + sel.length;
      if (!insideLink(from, end)) {
        md = md.slice(0, from) + link.wikilink + md.slice(end);
        injected = true;
        break;
      }
    }
    if (injected) continue;

    // Whitespace-flexible fallback (handles DOM-span joins that differ from rendered spaces)
    try {
      const pattern = sel.trim()
        .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        .replace(/\s+/g, '\\s+');
      const re = new RegExp(pattern, 'g');
      let m: RegExpExecArray | null;
      while ((m = re.exec(md)) !== null) {
        const start = m.index;
        const end = start + m[0].length;
        if (!insideLink(start, end)) {
          md = md.slice(0, start) + link.wikilink + md.slice(end);
          break;
        }
        if (re.lastIndex === start) re.lastIndex++; // avoid zero-width loop
      }
    } catch { /* unusual chars in selection — skip */ }
  }

  return normalizeWikilinks(md);
}

/** Byte ranges of every `[[...]]` (incl. `[[target|alias]]`) in the string. */
function wikilinkRanges(s: string): Array<[number, number]> {
  const ranges: Array<[number, number]> = [];
  const re = /\[\[[^[\]]*\]\]/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(s)) !== null) ranges.push([m.index, m.index + m[0].length]);
  return ranges;
}

/**
 * Collapse any accidental nesting into a single valid wikilink. Guards against
 * `[[[[x]]]]` and `[[a [[b]]]]` shapes that can arise if a note is re-saved or a
 * selection already contained bracket characters. Keeps only the outermost
 * `[[ ]]` pair and drops inner bracket markers, preserving the text between them.
 */
export function normalizeWikilinks(md: string): string {
  // Depth scan: keep only the outermost [[ ]] pair, dropping inner bracket
  // markers while preserving the text between them. This correctly flattens
  // both [[[[x]]]] and [[a [[b]]]] (whose closing-bracket runs are legitimate
  // for nested opens, so they must NOT be collapsed before scanning).
  let result = '';
  let depth = 0;
  for (let i = 0; i < md.length; i++) {
    if (md[i] === '[' && md[i + 1] === '[') {
      depth++;
      if (depth === 1) result += '[[';
      i++; // consume the second '['
      continue;
    }
    if (md[i] === ']' && md[i + 1] === ']') {
      if (depth > 0) {
        depth--;
        if (depth === 0) result += ']]';
      } else {
        result += ']]'; // stray close with no open — keep verbatim
      }
      i++; // consume the second ']'
      continue;
    }
    result += md[i];
  }

  // Unbalanced brackets mean malformed input the scan could corrupt — fall back
  // to a conservative run-collapse on the original rather than drop text.
  if (depth !== 0) {
    return md.replace(/\[{3,}/g, '[[').replace(/\]{3,}/g, ']]');
  }

  // Tidy any stray odd-length bracket runs the scan left behind.
  return result.replace(/\[{3,}/g, '[[').replace(/\]{3,}/g, ']]');
}

/** Compose a page `task` from its title and (possibly empty) body. */
function composeTask(title: string, body: string): string {
  // Line 1 = title, blank line, then banner + body. The blank line after the
  // title is what makes parseNoteTask treat only line 1 as the note title.
  return body
    ? `${title}\n\n${BOOK_NOTE_BANNER}\n\n${body}`
    : `${title}\n\n${BOOK_NOTE_BANNER}`;
}

/** Max body length that keeps `composeTask(title, body)` within the limit. */
function bodyBudget(title: string): number {
  const overhead = composeTask(title, 'x').length - 1; // header + 1 body char - that char
  return Math.max(1, OBSIDIAN_TASK_LIMIT - overhead);
}

/**
 * Emit an oversized block as a sequence of pages starting at `startPageNum`,
 * each within the per-page limit. The budget is recomputed from EACH page's
 * own title, because later page titles are longer (`(2)`, `(3)`, …) and would
 * otherwise overflow. Breaks at newline boundaries where possible, else a hard
 * cut. Returns the produced pages and the next free page number.
 */
function paginateOversizedBlock(
  docTitle: string,
  block: string,
  startPageNum: number,
): { pages: BookNotePage[]; nextPageNum: number } {
  const pages: BookNotePage[] = [];
  let pageNum = startPageNum;
  let rest = block;

  // Guard against pathological non-progress.
  while (rest.length > 0) {
    const title = bookNotePageTitle(docTitle, pageNum);
    const budget = bodyBudget(title);
    if (rest.length <= budget) {
      pages.push({ title, task: composeTask(title, rest) });
      pageNum += 1;
      rest = '';
      break;
    }
    const window = rest.slice(0, budget);
    const nl = window.lastIndexOf('\n');
    const cut = nl > 0 ? nl : budget;
    pages.push({ title, task: composeTask(title, rest.slice(0, cut)) });
    pageNum += 1;
    rest = rest.slice(cut).replace(/^\n/, '');
  }

  return { pages, nextPageNum: pageNum };
}

/** A reader's running summary for one chapter (chapter 0 for single-section docs). */
export interface ChapterSummary {
  chapter: number;
  text: string;
}

/**
 * Render the reader's running summaries as a leading `## Summary` section.
 * Multi-chapter docs get a `### Chapter N` sub-heading per summary; a single
 * summary (e.g. an article) is rendered plain under the heading. Empty in → ''.
 */
export function renderSummarySection(summaries: ChapterSummary[]): string {
  const valid = summaries
    .filter((s) => s.text.trim())
    .sort((a, b) => a.chapter - b.chapter);
  if (valid.length === 0) return '';
  const perChapter = valid.length > 1 || valid[0].chapter > 0;
  const lines: string[] = ['## Summary'];
  for (const s of valid) {
    lines.push('');
    if (perChapter) {
      lines.push(`### Chapter ${s.chapter + 1}`);
      lines.push('');
    }
    lines.push(s.text.trim());
  }
  return lines.join('\n').trim();
}

/**
 * Rebuild the entire Book_Note as an ordered list of pages from the current
 * annotation set (and any running summaries, which lead the note). Whole blocks
 * are packed greedily; a block is never split across pages unless that single
 * block (with its page header) cannot fit on a page of its own — in which case
 * only that block is split, still dropping nothing (Requirements 6.1, 6.6). An
 * empty set yields exactly one page (title + banner) so the note always exists.
 */
export function buildBookNotePages(
  docTitle: string,
  annotations: Annotation[],
  summaries: ChapterSummary[] = [],
): BookNotePage[] {
  const pages: BookNotePage[] = [];
  let pageNum = 1;
  let currentBlocks: string[] = [];

  const flush = () => {
    const title = bookNotePageTitle(docTitle, pageNum);
    const body = currentBlocks.join(BLOCK_SEPARATOR);
    pages.push({ title, task: composeTask(title, body) });
    pageNum += 1;
    currentBlocks = [];
  };

  // The summary section (if any) leads the note, then one block per annotation.
  const blocks: string[] = [];
  const summaryBlock = renderSummarySection(summaries);
  if (summaryBlock) blocks.push(summaryBlock);
  for (const annotation of annotations) blocks.push(renderAnnotationBlock(annotation));

  for (const block of blocks) {
    const titleForBlock = bookNotePageTitle(docTitle, pageNum);
    const budget = bodyBudget(titleForBlock);

    if (block.length > budget) {
      // Oversized single block: flush whatever is pending, then split this one
      // block across consecutive pages (budget recomputed per page).
      if (currentBlocks.length > 0) flush();
      const { pages: blockPages, nextPageNum } = paginateOversizedBlock(
        docTitle,
        block,
        pageNum,
      );
      pages.push(...blockPages);
      pageNum = nextPageNum;
      continue;
    }

    // Try to add the whole block to the current page; start a new page if it
    // would overflow.
    const tentative =
      currentBlocks.length > 0
        ? `${currentBlocks.join(BLOCK_SEPARATOR)}${BLOCK_SEPARATOR}${block}`
        : block;
    if (composeTask(titleForBlock, tentative).length <= OBSIDIAN_TASK_LIMIT) {
      currentBlocks.push(block);
    } else {
      if (currentBlocks.length > 0) flush();
      currentBlocks.push(block);
    }
  }

  if (currentBlocks.length > 0 || pages.length === 0) flush();
  return pages;
}
